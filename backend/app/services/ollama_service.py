"""
Ollama Service Module for PG Finder AI.

Manages communication with the local Ollama instance using the official
Python ollama library. Handles chat completion, connection health checks,
and graceful error handling for missing models or disconnected services.
"""

import os
from typing import Any, Dict, List, Optional
from dotenv import load_dotenv

# Load environment variables from .env file if present
load_dotenv()

try:
    import ollama
    from ollama import Client, ResponseError
except ImportError:  # pragma: no cover
    ollama = None
    Client = None
    ResponseError = Exception


class OllamaServiceError(Exception):
    """Base exception for Ollama service operations."""
    pass


class OllamaConnectionError(OllamaServiceError):
    """Raised when the backend cannot establish a connection to Ollama."""
    pass


class OllamaModelNotFoundError(OllamaServiceError):
    """Raised when the specified model is not installed/pulled in Ollama."""
    pass


class OllamaService:
    """
    Service wrapper for interacting with a local Ollama instance.
    """

    def __init__(
        self,
        host: Optional[str] = None,
        model: Optional[str] = None,
    ) -> None:
        """
        Initialize the Ollama service.

        Args:
            host: Ollama server endpoint (defaults to OLLAMA_HOST or http://localhost:11434).
            model: Model identifier (defaults to OLLAMA_MODEL or llama3.2:3b).
        """
        self.host: str = (
            host
            or os.getenv("OLLAMA_HOST", "http://localhost:11434").strip()
            or "http://localhost:11434"
        )
        self.model: str = (
            model
            or os.getenv("OLLAMA_MODEL", "llama3.2:3b").strip()
            or "llama3.2:3b"
        )

    def _get_client(self) -> Any:
        """Instantiates or validates the Ollama client."""
        if Client is None:
            raise OllamaServiceError(
                "The official 'ollama' Python library is not installed. "
                "Install it with 'pip install ollama'."
            )
        return Client(host=self.host)

    def chat(
        self,
        message: str,
        system_prompt: Optional[str] = None,
    ) -> str:
        """
        Sends a user message to the configured Ollama model and returns its response.

        Args:
            message: The user's input prompt or inquiry.
            system_prompt: Optional system instruction for tone/persona.

        Returns:
            The text response generated by Ollama.

        Raises:
            OllamaConnectionError: If Ollama daemon is unreachable.
            OllamaModelNotFoundError: If the target model has not been downloaded.
            OllamaServiceError: For any unexpected API or validation failures.
        """
        if not message or not message.strip():
            raise ValueError("Message cannot be empty.")

        client = self._get_client()

        messages: List[Dict[str, str]] = []
        if system_prompt and system_prompt.strip():
            messages.append({"role": "system", "content": system_prompt.strip()})
        messages.append({"role": "user", "content": message.strip()})

        try:
            response = client.chat(
                model=self.model,
                messages=messages,
                options={
                    "num_predict": 250,
                    "temperature": 0.7,
                },
            )

            # Extract message content defensively across library versions
            if hasattr(response, "message") and hasattr(response.message, "content"):
                return str(response.message.content).strip()
            elif isinstance(response, dict) and "message" in response:
                content = response["message"].get("content", "")
                return str(content).strip()

            return str(response).strip()

        except ResponseError as e:
            err_msg = str(e)
            status_code = getattr(e, "status_code", None)
            if (
                status_code == 404
                or "not found" in err_msg.lower()
                or "try pulling it first" in err_msg.lower()
            ):
                raise OllamaModelNotFoundError(
                    f"Ollama model '{self.model}' was not found. "
                    f"Run 'ollama pull {self.model}' in your terminal to download it."
                ) from e
            raise OllamaServiceError(f"Ollama API error: {err_msg}") from e

        except (ConnectionRefusedError, ConnectionError) as e:
            raise OllamaConnectionError(
                f"Failed to connect to local Ollama service at '{self.host}'. "
                "Ensure Ollama is running (e.g. check Windows tray or run 'ollama serve')."
            ) from e

        except Exception as e:
            err_str = str(e).lower()
            if (
                "connection refused" in err_str
                or "connecterror" in err_str
                or "failed to establish a new connection" in err_str
                or "all connection attempts failed" in err_str
            ):
                raise OllamaConnectionError(
                    f"Failed to connect to local Ollama service at '{self.host}'. "
                    "Ensure Ollama is running (e.g. check Windows tray or run 'ollama serve')."
                ) from e

            if "not found" in err_str and ("model" in err_str or self.model.lower() in err_str):
                raise OllamaModelNotFoundError(
                    f"Ollama model '{self.model}' was not found. "
                    f"Run 'ollama pull {self.model}' in your terminal to download it."
                ) from e

            raise OllamaServiceError(
                f"Unexpected error while communicating with Ollama: {e}"
            ) from e

    def get_status(self) -> Dict[str, Any]:
        """
        Performs a non-throwing diagnostic check against Ollama.

        Returns:
            Dict containing connection status, model verification, and model list.
        """
        try:
            client = self._get_client()
            models_data = client.list()

            # Handle both object attributes and dict responses
            models_list = getattr(models_data, "models", None)
            if models_list is None and isinstance(models_data, dict):
                models_list = models_data.get("models", [])

            model_names: List[str] = []
            if models_list:
                for m in models_list:
                    name = getattr(m, "model", None) or getattr(m, "name", None)
                    if not name and isinstance(m, dict):
                        name = m.get("model") or m.get("name")
                    if name:
                        model_names.append(str(name))

            target = self.model.lower()
            model_found = any(
                target == m.lower()
                or target.split(":")[0] == m.lower().split(":")[0]
                for m in model_names
            )

            return {
                "connected": True,
                "host": self.host,
                "model": self.model,
                "model_available": model_found,
                "installed_models": model_names,
            }
        except Exception as e:
            return {
                "connected": False,
                "host": self.host,
                "model": self.model,
                "model_available": False,
                "error": str(e),
                "installed_models": [],
            }


# Singleton service provider
_default_service: Optional[OllamaService] = None


def get_ollama_service() -> OllamaService:
    """Returns the singleton instance of OllamaService."""
    global _default_service
    if _default_service is None:
        _default_service = OllamaService()
    return _default_service
